import { expect, test } from '@playwright/test'
import { accountMenu, DEMO, emailLink, newEmail, openBoard, PASSWORD, signIn, signUp, startAsGuest } from './helpers.ts'

test('T-300 T-764 continue as guest opens a board with the column names only, no example cards @smoke', async ({ page }) => {
  await startAsGuest(page)
  for (const title of ['To Do', 'In Progress', 'Done']) {
    await expect(page.getByRole('region', { name: title }).getByText('No cards here yet')).toBeVisible()
  }
  await expect(page.getByText(/guest account/)).toBeVisible()
})

test('T-301 sign up, verify, sign out, sign in again; data persists @smoke', async ({ page }) => {
  const email = await signUp(page)
  await openBoard(page, 'Persistent plans', [['Remember me']])
  await accountMenu(page, 'Sign out')
  await expect(page.getByRole('heading', { name: 'Sign in to Task Manager' })).toBeVisible()
  await signIn(page, email)
  await page.getByRole('button', { name: /switch board/ }).click()
  await page.getByRole('menuitemradio', { name: 'Persistent plans' }).click()
  await expect(page.getByText('Remember me')).toBeVisible()
})

test('T-321 an unverified account sees the verify message and can resend the email', async ({ page }) => {
  const email = newEmail()
  await page.goto('/signin')
  await page.getByRole('link', { name: 'Create an account' }).click()
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Password', { exact: true }).fill(PASSWORD)
  await page.getByLabel('Repeat password').fill(PASSWORD)
  await page.getByRole('button', { name: 'Create account' }).click()
  await expect(page.getByRole('heading', { name: 'Check your inbox' })).toBeVisible()
  const first = await emailLink(page.request, email)
  await signIn(page, email)
  await expect(page.getByText('Verify your email to sign in.')).toBeVisible()
  await page.getByRole('button', { name: 'Send a new link' }).click()
  await page.getByRole('button', { name: 'Resend email' }).click()
  await expect(page.getByText('We sent a new link.', { exact: false })).toBeVisible()
  await expect.poll(() => emailLink(page.request, email)).not.toBe(first)
  await page.goto(await emailLink(page.request, email))
  await expect(page.getByRole('heading', { name: DEMO })).toBeVisible()
})

test('T-318 forgot password: reset link sets a new password; the old one fails', async ({ page }) => {
  const email = await signUp(page)
  await accountMenu(page, 'Sign out')
  await page.getByRole('link', { name: 'Forgot password?' }).click()
  await page.getByLabel('Email').fill(email)
  await page.getByRole('button', { name: 'Send reset link' }).click()
  await page.goto(await emailLink(page.request, email, '/reset-password'))
  await page.getByLabel('New password', { exact: true }).fill('Brand-New-Pass-7')
  await page.getByLabel('Repeat new password').fill('Brand-New-Pass-7')
  await page.getByRole('button', { name: 'Save new password' }).click()
  // A returning user lands on the start page (T-729).
  await expect(page.getByRole('heading', { name: 'Your work', level: 1 })).toBeVisible()
  await accountMenu(page, 'Sign out')
  await signIn(page, email)
  await expect(page.getByRole('alert')).toBeVisible()
  await signIn(page, email, 'Brand-New-Pass-7')
  await expect(page.getByRole('heading', { name: 'Your work', level: 1 })).toBeVisible()
})

test('T-319 a password change in one browser signs out a second browser', async ({ page, browser }) => {
  const email = await signUp(page)
  const other = await (await browser.newContext()).newPage()
  await signIn(other, email)
  await expect(other.getByRole('heading', { name: 'Your work', level: 1 })).toBeVisible()
  await accountMenu(page, 'Change password')
  await page.getByLabel('Current password').fill(PASSWORD)
  await page.getByLabel('New password').fill('Another-Pass-99')
  await page.getByRole('button', { name: 'Save password' }).click()
  await expect(page.getByText('Password saved. Other devices were signed out.')).toBeVisible()
  await other.reload()
  await expect(other.getByRole('heading', { name: 'Sign in to Task Manager' })).toBeVisible()
  await page.getByRole('dialog').getByRole('button', { name: 'Done' }).click()
  await page.reload()
  await expect(page.getByRole('heading', { name: DEMO })).toBeVisible()
})

