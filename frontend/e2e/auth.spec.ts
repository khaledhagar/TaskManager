test('T-509 sign up refuses a weak password, accepts a medium one, and offers Google @smoke', async ({ page }) => {
  await page.goto('/signup')
  await expect(page.getByRole('link', { name: 'Continue with Google' })).toBeVisible()
  await page.getByLabel('Email').fill(newEmail())
  const password = page.getByLabel('Password', { exact: true })
  await password.fill('password123')
  await expect(page.getByText('Password strength: Weak')).toBeVisible()
  await expect(page.getByText('This password is too common.')).toBeVisible()
  await page.getByRole('button', { name: 'Create account' }).click()
  await expect(page.getByText('This password is too weak.')).toBeVisible()
  await expect(page).toHaveURL(/\/signup$/)
  await password.fill('correct-horse')
  await expect(page.getByRole('meter', { name: 'Password strength' })).toHaveAttribute('aria-valuetext', 'Medium')
  await page.getByLabel('Repeat password').fill('correct-hors')
  await page.getByRole('button', { name: 'Create account' }).click()
  await expect(page.getByText("Passwords don't match.")).toBeVisible()
  await page.getByLabel('Repeat password').fill('correct-horse')
  await page.getByRole('button', { name: 'Create account' }).click()
  await expect(page.getByRole('heading', { name: 'Check your inbox' })).toBeVisible()
})
